const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');

const source = fs.readFileSync('static/js/main.js', 'utf8');
const setup = source.slice(source.indexOf('function setupResponsiveNavigation()'),
    source.indexOf("document.addEventListener('DOMContentLoaded', function ()"));
const html = fs.readFileSync('templates/index.html', 'utf8');
const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'https://qa.invalid' });
const w = dom.window, d = w.document;
let change;
const media = { matches: true, addEventListener: (event, callback) => { change = callback; } };
w.matchMedia = () => media;
w.eval(setup + '\nsetupResponsiveNavigation();');
const nav = d.getElementById('app-navigation');
const toggle = d.getElementById('navigation-toggle');
const close = d.getElementById('navigation-close');
const backdrop = d.getElementById('navigation-backdrop');
const content = d.getElementById('app-content');
const main = d.getElementById('main-content');
assert.equal(nav.inert, true);
assert.equal(content.inert, false);
assert.equal(toggle.getAttribute('aria-expanded'), 'false');
toggle.click();
assert.equal(nav.inert, false);
assert.equal(content.inert, true);
assert.equal(backdrop.hidden, false);
assert.equal(nav.getAttribute('aria-modal'), 'true');
assert.equal(nav.getAttribute('role'), 'dialog');
assert.equal(d.activeElement, close);
close.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true }));
const last = nav.querySelector('button[aria-controls="userDropdown"]');
assert.equal(d.activeElement, last);
last.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Tab', bubbles: true }));
assert.equal(d.activeElement, close);
close.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
assert.equal(d.activeElement, toggle);
assert.equal(content.inert, false);
assert.equal(nav.inert, true);
toggle.click();
backdrop.click();
assert.equal(toggle.getAttribute('aria-expanded'), 'false');
toggle.click();
nav.querySelector('.nav-link').click();
assert.equal(d.activeElement, main);
assert.equal(nav.inert, true);
toggle.click();
media.matches = false;
change();
assert.equal(nav.inert, false);
assert.equal(content.inert, false);
assert.equal(nav.hasAttribute('aria-modal'), false);
assert.equal(d.activeElement, nav.querySelector('.nav-link'));
media.matches = true;
change();
assert.equal(nav.inert, true);
assert.equal(d.activeElement, toggle);
assert.equal(backdrop.hidden, true);
assert(source.includes('for="email-address"'));
assert(source.includes('for="jd-job-title"'));
assert(source.includes('aria-label="Number of candidates"'));
assert(source.includes('aria-label="Search reports"'));
assert(source.includes('autocomplete="new-password"'));
const css = fs.readFileSync('static/css/style.css', 'utf8');
assert(css.includes('#results-area.opacity-0, #bottom-chat-container.opacity-0 { visibility: hidden; }'));
assert.match(css, /#chat-input\s*\{[^}]*padding-right:\s*104px/s);
assert(css.includes('@media (prefers-reduced-motion: reduce)'));
assert(source.includes('aria-label="Upload job description"'));
assert(source.includes('role="button" tabindex="0" aria-label="Search using the sample job description"'));
const cards = source.slice(source.indexOf('categoryCards.forEach(card =>'), source.indexOf('// Handle main send button click'));
const card = d.createElement('div');
card.className = 'search-category-card';
card.innerHTML = '<h3>Sample Job Description</h3>';
d.body.appendChild(card);
let searches = 0;
w.eval(`{const categoryCards = document.querySelectorAll('.search-category-card');
    const chatInput = {value:''};
    const handleSendMessage = () => window.recordSearch();
    ${cards}}`);
w.recordSearch = () => { searches++; };
for (const key of ['Enter', ' ']) {
    const event = new w.KeyboardEvent('keydown', {key, bubbles:true, cancelable:true});
    card.dispatchEvent(event);
    assert(event.defaultPrevented);
}
card.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Enter', repeat:true, bubbles:true}));
card.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Escape', bubbles:true}));
assert.equal(searches, 2, 'Each keyboard activation must search once; held/unrelated keys must not search');
console.log('Responsive navigation: focus trap, Escape, backdrop, routing, resize, labels passed');
dom.window.close();
