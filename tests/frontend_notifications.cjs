const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const dom=new JSDOM('',{url:'https://qa.invalid',runScripts:'outside-only'}),w=dom.window,d=w.document;
const timers=[];w.setTimeout=(fn,delay)=>{timers.push({fn,delay});return timers.length;};w.clearTimeout=()=>{};
w.eval(fs.readFileSync('static/js/notifications.js','utf8'));
const show=w.AppNotifications.show;
const first=show('<img src=x onerror=bad()>','error');
assert.equal(first.querySelectorAll('img,[onerror]').length,0);
assert(first.textContent.includes('<img src=x onerror=bad()>'));
assert.equal(first.getAttribute('role'),'alert');
assert.equal(timers.length,0,'Errors must not disappear before the user can read them');
assert.equal(show('<img src=x onerror=bad()>','error'),first);
show('Scheduled','success');show('Meeting link saved','info');show('Email accepted','success');
assert.equal(d.querySelector('#app-notifications').children.length,4);
show('Audit warning','warning');
assert.equal(d.querySelector('#app-notifications').children.length,4);
assert.equal(first.isConnected,false);
d.querySelector('.app-notification button').click();
assert.equal(d.querySelector('#app-notifications').children.length,3);
assert(timers.some(t=>t.delay===12000));
const css=fs.readFileSync('static/css/components.css','utf8');
assert(css.includes('grid-template-columns: 20px minmax(0, 1fr) 32px'));
assert(css.includes('calc(100vw - 24px)'));
assert(css.includes('overflow-wrap: anywhere'));
const overlay=d.createElement('div');overlay.className='workspace-overlay';
overlay.innerHTML='<section class="workspace-dialog"><header><button>Close</button></header><div class="workspace-dialog-body">Form</div><footer><button>Save</button></footer></section>';
d.body.append(overlay);
const inDialog=show('Review the selected date','error');
assert(inDialog.closest('.workspace-dialog'),'Modal errors must be in the dialog flow, not over its controls');
assert.equal(inDialog.parentElement.nextElementSibling.className,'workspace-dialog-body');
assert.equal(show('Review the selected date','error'),inDialog);
assert.equal(d.querySelectorAll('#app-notifications').length,1,'A modal must not duplicate the global root ID');
assert(css.includes('display: none; pointer-events: none;'),'Background notifications must not cover modal controls');
overlay.remove();
assert.equal(show('After dialog','info').parentElement.id,'app-notifications');
overlay.innerHTML='<section class="workspace-dialog"><header>Administration</header><form class="workspace-form"><div class="workspace-dialog-body">Fields</div><footer>Save</footer></form></section>';
d.body.append(overlay);
const adminError=show('Fictional administrative error','error');
assert.equal(adminError.parentElement.nextElementSibling.tagName,'FORM','Nested modal forms must not cause insertBefore errors');
overlay.remove();
dom.window.close();
console.log('Notification UI passed: stacking, bounded queue, deduplication, safe text, persistent errors, in-dialog feedback, unobstructed modal controls and responsive dismissal.');
