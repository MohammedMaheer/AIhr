const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const source=fs.readFileSync('static/js/main.js','utf8');
const moduleSource=fs.readFileSync('static/js/recruiter-outreach.js','utf8');
const flush=()=>new Promise(resolve=>setImmediate(resolve));
async function run(){
 const dom=new JSDOM('<div id="app-shell"><button id="open">Open</button></div>',{url:'https://qa.invalid',runScripts:'outside-only'});
 const w=dom.window,d=w.document;
 w.currentUser={id:7,full_name:'Super Admin'};
 w.searchResultsData={job_title:'Position',query:'Networks and Information Security Team Lead onsite in Riyadh, KSA with 5 years experience. Salary SAR 7000-10000/month'};
 const notices=[];w.showNotification=(...v)=>notices.push(v);
 const status={success:true,microsoft:{connected:true,reconnect_required:false,capabilities:{email:true,calendar:true},account_email:'hr@example.invalid'},google:{connected:false,capabilities:{email:false,calendar:false}},smtp:{configured:false}};
 let posts=0,failSend=false,previewPayload=null,sendPayload=null;
 w.fetch=async(url,options={})=>{
  if(url==='/api/integrations/status')return{ok:true,json:async()=>status};
  if(url==='/api/preview-candidate-email'){previewPayload=JSON.parse(options.body);return{ok:true,json:async()=>({success:true,body_html:'<p>Fictional branded preview</p>'})};}
  if(url==='/api/send-candidate-email'){sendPayload=JSON.parse(options.body);posts++;if(failSend)throw new TypeError('Synthetic uncertain transport');return{ok:true,json:async()=>({success:true})};}
  throw new Error('Unexpected network call '+url);
 };
 w.eval(source.slice(source.indexOf('function bindScheduleDialog('),source.indexOf('function closeInterviewModal()')));
 w.eval(moduleSource);
 const ctx=w.RecruiterOutreach.context({candidateName:'Fictional Candidate',candidateEmail:'fixture@example.invalid',searchResultId:'23',jobApplicationId:'314'});
 assert.equal(ctx.position,'Networks and Information Security Team Lead');
 assert.equal(ctx.location,'Riyadh, KSA');
 assert.equal(ctx.recruiter,'Recruitment Team');
 const content=w.RecruiterOutreach.message('details',ctx);
 assert(content.body.includes('Team leadership experience'));
 assert(content.body.includes('SAR 7000-10000/month'));
 assert(!/nationality|residency/i.test(content.body),'Sensitive identity details must not be inferred or included by default');
 assert(!w.RecruiterOutreach.message('details',w.RecruiterOutreach.context({useSearch:false})).body.includes('SAR'),'A different context must not inherit salary');
 const schedule=d.createElement('div');schedule.innerHTML='<select id="interview-provider"><option value="meet">Google Meet</option></select><p></p>';d.body.append(schedule);
 await w.RecruiterOutreach.configureSchedule(schedule);
 assert.deepEqual([...schedule.querySelector('select').options].map(o=>o.value),['none','teams']);schedule.remove();
 d.getElementById('open').focus();
 w.RecruiterOutreach.open(ctx);await flush();
 let modal=d.querySelector('[data-email-composer]'),form=modal.querySelector('form');
 assert.equal(form.elements.transport.options.length,1);
 assert.equal(form.elements.position.value,ctx.position);
 assert.equal(modal.querySelector('[data-send]').disabled,true);
 assert.equal(modal.querySelector('iframe').getAttribute('sandbox'),'');
 form.elements.message.value='My manually edited message';form.elements.message.dispatchEvent(new w.Event('input',{bubbles:true}));
 form.elements.template.value='followup';form.elements.template.dispatchEvent(new w.Event('change'));
 assert.equal(modal.querySelector('.outreach-replace').hidden,false);
 assert.equal(form.elements.message.value,'My manually edited message');
 modal.querySelector('[data-replace]').click();
 assert(form.elements.message.value.includes('following up'));
 modal.querySelector('[data-preview]').click();await flush();
 assert.equal(modal.querySelector('[data-send]').disabled,false);
 assert.equal(previewPayload.job_application_id,'314');
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await flush();
 assert.equal(posts,1,'Pending send must not be submitted twice');
 assert.equal(sendPayload.job_application_id,'314');
 assert.equal(modal.querySelector('[data-send]').disabled,true,'Accepted exact draft must not resend');
 modal.querySelector('[data-close]').click();await flush();
 w.RecruiterOutreach.open(ctx);await flush();
 modal=d.querySelector('[data-email-composer]');form=modal.querySelector('form');
 assert(form.elements.message.value.includes('following up'),'Draft should survive closing');
 form.elements.message.value='New explicit draft';form.elements.message.dispatchEvent(new w.Event('input',{bubbles:true}));
 modal.querySelector('[data-preview]').click();await flush();failSend=true;
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await flush();
 assert.equal(posts,2);assert.equal(modal.querySelector('[data-send]').disabled,true);
 assert(modal.querySelector('.outreach-feedback').textContent.includes('Check Sent Items'));
 dom.window.close();

 const progress=new JSDOM('<div id="candidate-list"></div><div id="results-container"></div>',{runScripts:'outside-only'}),pw=progress.window;
 pw.eval(source.slice(source.indexOf('    // Make showLoadingMessage available globally'),source.indexOf('    function showRealTimeProgress()')));
 pw.showLoadingMessage();pw.updateSearchProgress({status:'processing',progress:{step:'generating_scorecards',current_candidate:9,total_candidates:20,progress_percent:45,cache_hits:3}});
 assert(pw.document.body.textContent.includes('9 of 20 profiles reviewed'));
 assert(!/Vertex|Gemini|cache|generating_scorecards/.test(pw.document.body.textContent));
 assert.equal(pw.document.getElementById('search-progress-bar').getAttribute('aria-valuenow'),'45');
 pw.updateSearchProgress({status:'pending',progress:{}});
 assert.equal(pw.document.getElementById('search-progress-bar').hasAttribute('aria-valuenow'),false);
 progress.window.close();
 console.log('Outreach UI passed: query prefills, neutral templates, connected-provider filtering, draft preservation, reviewed single sends, uncertain-outcome guard and honest animated progress.');
}
run().catch(error=>{console.error(error);process.exitCode=1;});
